"""Generate an offline inflection index from pinned ECDICT and UniMorph sources."""

import argparse
import csv
import hashlib
import json
import re
from pathlib import Path

SITE = Path(__file__).resolve().parents[1]
WORD = re.compile(r"[a-z]+(?:[ -][a-z]+)*\Z", re.ASCII)
VERB = re.compile(r"\b(?:v|vt|vi)\.", re.IGNORECASE)
SLOTS = "3ipd"
UNIMORPH_SHA256 = "20a191cefdc7cad6fa74b00f49d6f658684f17b14541aae372e5a3d5a8c15c67"
UNIMORPH_TAGS = ("V;PRS;3;SG", "V;V.PTCP;PRS", "V;PST", "V;V.PTCP;PST")
# Verified additions and corrections to ECDICT's four slots. Separate spellings with commas.
OVERRIDES = {
    "babysit": ("babysits", "babysitting", "babysat", "babysat"),
    "be": ("am,is,are", "being", "was,were", "been"),
    "beat": ("beats", "beating", "beat", "beaten"),
    "bid": ("bids", "bidding", "bid,bade", "bid,bidden"),
    "burn": ("burns", "burning", "burned,burnt", "burned,burnt"),
    "can": ("cans", "canning", "canned", "canned"),
    "get": ("gets", "getting", "got", "got,gotten"),
    "learn": ("learns", "learning", "learned,learnt", "learned,learnt"),
    "mow": ("mows", "mowing", "mowed", "mown,mowed"),
    "prove": ("proves", "proving", "proved", "proved,proven"),
    "sew": ("sews", "sewing", "sewed", "sewn,sewed"),
    "shear": ("shears", "shearing", "sheared", "shorn,sheared"),
    "shrink": ("shrinks", "shrinking", "shrank,shrunk", "shrunk"),
    "sow": ("sows", "sowing", "sowed", "sown,sowed"),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", type=Path)
    parser.add_argument("unimorph", type=Path)
    args = parser.parse_args()
    source = json.loads((SITE / "wordbooks/dataset-lock.json").read_text(encoding="utf-8"))["source"]
    with args.csv.open("rb") as stream:
        if hashlib.file_digest(stream, "sha256").hexdigest() != source["csvSha256"]:
            parser.error("CSV does not match the pinned ECDICT source")

    with args.unimorph.open("rb") as stream:
        if hashlib.file_digest(stream, "sha256").hexdigest() != UNIMORPH_SHA256:
            parser.error("TSV does not match the pinned UniMorph source")

    index = {}
    with args.csv.open(encoding="utf-8", newline="") as stream:
        for row in csv.DictReader(stream):
            base = row["word"]
            if not WORD.fullmatch(base):
                continue
            fields = dict(part.split(":", 1) for part in row["exchange"].split("/") if ":" in part)
            gloss = row["translation"].replace(r"\n", " ")
            if VERB.search(gloss):
                forms = tuple(fields.get(slot, "") for slot in SLOTS)
                forms = tuple(form if WORD.fullmatch(form) else "" for form in forms)
                if forms[0] == base:
                    forms = ("", *forms[1:])
                index[base] = forms

    supplemental = {}
    with args.unimorph.open(encoding="utf-8", newline="") as stream:
        for row in csv.reader(stream, delimiter="\t"):
            if len(row) != 3:
                continue
            base, form, tag = row
            if (
                base in index
                and tag in UNIMORPH_TAGS
                and WORD.fullmatch(form)
                and (tag != UNIMORPH_TAGS[0] or form != base)
            ):
                supplemental.setdefault((base, tag), set()).add(form)
    for base, forms in index.items():
        index[base] = tuple(
            form or ",".join(sorted(supplemental.get((base, tag), ())))
            for tag, form in zip(UNIMORPH_TAGS, forms)
        )
    index = {base: forms for base, forms in index.items() if any(forms)}
    index.update(OVERRIDES)
    records = "\n".join(f"{base}|{'|'.join(forms)}" for base, forms in sorted(index.items()))
    output = SITE / "verb-inflections.mjs"
    output.write_text(
        "// Generated by tools/build-verb-inflections.py. ECDICT (MIT) and UniMorph (CC BY-SA 3.0).\n"
        "// Data sources and attribution: wordbooks/NOTICE.txt.\n"
        "// Column order: base, third-person singular, present participle, past, past participle.\n"
        "export default `" + records + "`;\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{len(index)} entries written to {output.name}")


if __name__ == "__main__":
    main()
